"""Synthetic price data generator for backtesting.

Supports both Deriv CSPRNG-style synthetic indices AND Blueberry Markets'
proprietary synthetic index algorithm.  Each broker has different price
generation mechanisms, spread models, and asset behaviors.

Key differences:
- Deriv: CSPRNG (Mersenne Twister) with GARCH-like variance scheduling
- Blueberry Markets: In-house proprietary algorithm with distinct index classes
  (SYN, SURGE, DROP, LEAP) each with unique behavioral characteristics

Reference:
- Deriv documentation: "The numbers are generated by a cryptographically
  secure random number generator"
- Blueberry Markets: Proprietary algorithmic modeling framework for
  synthetic indices (SYN100, SURGE50, DROP75, LEAP100, etc.)
- Engle (1982) "Autoregressive Conditional Heteroscedasticity"
- Bollerslev (1986) "Generalized ARCH"
"""

from __future__ import annotations

import math
import random
import time
from dataclasses import dataclass, field
from enum import Enum
from typing import Iterator

from synthetic_trader.domain import Tick


# ── Broker Type ──────────────────────────────────────────────────


class BrokerType(str, Enum):
    """Supported broker types with different price generation mechanisms."""
    DERIV = "deriv"
    BLUEBERRY = "blueberry"


# ── GARCH State ──────────────────────────────────────────────────


@dataclass
class GARCHParams:
    """Parameters for the GARCH/EGARCH variance scheduling process.

    These are calibrated to match the empirical properties of
    synthetic indices from different brokers:
    - omega: long-run variance intercept
    - alpha: shock magnitude coefficient
    - beta: variance persistence
    - gamma: asymmetry/leverage (negative returns increase vol more)
    """

    omega: float = 0.0000016
    alpha: float = 0.06
    beta: float = 0.92
    gamma: float = -0.02

    @property
    def persistence(self) -> float:
        """Total persistence: alpha + beta + gamma/2."""
        return self.alpha + self.beta + self.gamma / 2.0

    @property
    def long_run_variance(self) -> float:
        """Unconditional (long-run) variance."""
        p = self.persistence
        if p >= 1.0:
            return self.omega / 1e-6
        return self.omega / (1.0 - p)


# ── Spread Model ─────────────────────────────────────────────────


@dataclass
class SpreadModel:
    """Spread model for a synthetic index.

    Different brokers have different spread characteristics:
    - Deriv: Tight, native spreads controlled end-to-end
    - Blueberry: Markups and variance during non-peak hours
    """

    base_spread_pct: float = 0.001  # Base spread as % of price
    spread_noise: float = 0.01     # Random noise added to spread
    peak_hour_spread_mult: float = 1.0   # Spread multiplier during peak hours
    off_peak_spread_mult: float = 1.5    # Spread multiplier during off-peak hours

    def compute_spread(self, price: float, hour: int, rng: random.Random) -> float:
        """Compute spread for a given price and hour."""
        base = price * self.base_spread_pct

        # Apply time-of-day spread multiplier
        # Off-peak: 22:00-06:00 UTC (Asian session)
        if 22 <= hour or hour < 6:
            base *= self.off_peak_spread_mult
        else:
            base *= self.peak_hour_spread_mult

        # Add noise
        noise = rng.random() * self.spread_noise * price
        return base + noise


